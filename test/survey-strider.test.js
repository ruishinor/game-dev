import test from 'node:test';
import assert from 'node:assert/strict';
import {makeGame,makeChar,place,enemyOf,isolate} from './helpers.js';
import {equipItem,unequipSlot,craftRecipe} from '../server/sim/progress.js';
import {petCommand,renameCompanion,manageCompanion,companionRoster} from '../server/sim/companion.js';
import {tickSurveyStrider} from '../server/sim/survey-strider.js';
import {groundSegmentClear} from '../server/sim/ground-navigation.js';
const id='survey_strider_link';
const eligible=()=>makeChar('surveyor',{level:4,attunements:['resonance'],inventory:[id,'brine_calibrator'],equipped:{device:'brine_calibrator',implant:null,glyph:null},survey:'signal_done',brineStage:3});
test('legacy ownership migrates to permanent learned deployment without replacing gear',()=>{
 const g=makeGame(),m=g.addPlayer(makeChar('symbiotech')),p=g.addPlayer(eligible()),other=g.addPlayer(makeChar('vanguard',{inventory:[id]}));const original=m.companion;
 assert.equal(p.companion,null);assert.equal(p.char.striderLearned,true);assert.equal(p.char.inventory.includes(id),false);
 assert.equal(p.char.equipped.device,'brine_calibrator');
 assert.equal(manageCompanion(g,other,'summon').ok,false);
 assert.ok(manageCompanion(g,p,'summon').ok);const c=p.companion;assert.equal(c.type,'survey_strider');assert.ok(groundSegmentClear(c,c,.9));
 assert.equal(g.privateState(p).comp,c.id);assert.equal(g.metaFor(c).o,p.id);
 assert.equal(manageCompanion(g,p,'summon').ok,false);g.refreshStats(p);assert.equal(p.companion,c);
 assert.ok(petCommand(g,p,'stay').ok);assert.ok(renameCompanion(g,p,'Field Walker').ok);
 assert.ok(unequipSlot(g,p,'device').ok);assert.equal(p.companion,c);
 p.combatUntil=g.time+1000;assert.equal(manageCompanion(g,p,'dismiss').ok,false);p.combatUntil=0;
 assert.ok(manageCompanion(g,p,'dismiss').ok);assert.equal(g.ents.has(c.id),false);assert.equal(m.companion,original);
 assert.ok(manageCompanion(g,p,'summon').ok);assert.equal(p.companion.name,'Field Walker');
 const saved={...p.char,equipped:{...p.char.equipped},inventory:[...p.char.inventory]};g.removePlayer(p.id);const restored=g.addPlayer(saved);
 assert.equal(restored.companion.name,'Field Walker');assert.equal(restored.companion.mode,'stay');
});
test('craft learns only after valid transaction and no second recipe or gear requirement',()=>{
 const g=makeGame(),p=g.addPlayer(makeChar('surveyor',{level:4,attunements:['resonance'],survey:'signal_done',brineStage:3,materials:{sentinel_alloy:4,mire_fibre:2,resonance_fragment:1}}));
 assert.equal(craftRecipe(g,p,id).ok,false);place(p,49,-36.5);assert.ok(craftRecipe(g,p,id).ok);
 assert.equal(p.companion,null);assert.deepEqual(p.char.materials,{});assert.equal(p.char.striderLearned,true);assert.equal(p.char.inventory.includes(id),false);
 assert.equal(companionRoster(g,p)[0].available,true);assert.equal(craftRecipe(g,p,id).ok,false);
 assert.ok(manageCompanion(g,p,'summon').ok);
});
test('scan supplies bounded power once per interval; keeps manual marks and neutral protections',()=>{
 const g=makeGame(),p=g.addPlayer(eligible()),e=enemyOf(g,'skitter');isolate(g,e);
 assert.ok(manageCompanion(g,p,'summon').ok);const c=p.companion;place(p,0,25);c.x=1;c.z=25;e.x=4;e.z=25;e.state='idle';
 g.time=2000;c.nextPulse=0;p.target=e.id;assert.ok(petCommand(g,p,'assist').ok);g.time+=500;
 p.res=40;const hp=e.hp,before=e.threat.size;
 p.surveyKit.mark={id:999,until:g.time+1000};tickSurveyStrider(g,c,.05);assert.equal(p.res,40);assert.equal(p.surveyKit.mark.id,999);
 p.surveyKit.mark=null;c.nextPulse=0;tickSurveyStrider(g,c,.05);assert.equal(p.surveyKit.mark?.source,c.id);assert.equal(p.res,55);assert.equal(e.hp,hp);assert.equal(e.threat.size,before);
 p.surveyKit.mark=null;tickSurveyStrider(g,c,.05);assert.equal(p.res,55);assert.equal(p.surveyKit.mark,null);
 g.time+=9000;const neutral=enemyOf(g,'sinter_grazer');neutral.state='idle';neutral.threat.clear();neutral.x=4;neutral.z=25;p.target=neutral.id;tickSurveyStrider(g,c,.05);assert.equal(p.surveyKit.mark,null);
 p.target=e.id;p.res=95;tickSurveyStrider(g,c,.05);assert.equal(p.res,100);
 p.dead=true;tickSurveyStrider(g,c,.05);assert.equal(c.act,'dormant');
});
