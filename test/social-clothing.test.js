test('social purchase is unique, owned, class-independent and does not change armor stats or shields',()=>{
 const g=makeGame(),p=g.addPlayer(makeChar('vanguard',{credits:20,inventory:['field_chest'],equipped:{chest:'field_chest'}}));
 const npc=g.objects.find(x=>x.type==='quartermaster');place(p,npc.x,npc.z+2);assert.ok(openVendor(g,p,npc.id).ok);
 const order={op:'buy',id:'social_service_coat',qty:1,ticket:p.vendor.ticket,rev:p.vendor.rev};
 assert.ok(vendorState(g,p).buy.some(x=>x.id===order.id&&x.cosmetic));
 assert.ok(tradeVendor(g,p,order).ok);assert.equal(p.char.credits,12);
 assert.equal(tradeVendor(g,p,order).ok,false);
 assert.equal(tradeVendor(g,p,{...order,rev:p.vendor.rev}).ok,false);
 assert.equal(p.char.credits,12);
 const stats=p.stats,buff={k:'shield',v:10,until:g.time+1000};p.buffs.push(buff);
 const version=p.metaVer;
 assert.deepEqual(g.metaFor(p).av,{chest:'field_chest'});
 assert.ok(equipItem(g,p,order.id).ok);
 assert.equal(p.stats,stats);assert.ok(p.buffs.includes(buff));
 assert.equal(p.char.equipped.chest,'field_chest');assert.equal(g.metaFor(p).sv,'service');
 assert.equal(g.metaFor(p).av,undefined,'concealed armor identity is not projected');
 assert.ok(p.metaVer>version);assert.equal(g.metaFor(p).inventory,undefined);
 assert.equal(equipItem(g,p,'social_relay_coat').ok,false);
 assert.equal(publicSocialVisual({equipped:{social_torso:order.id},inventory:[]}),null);
 for(const id of ['constructor','__proto__','x/../y'])assert.equal(socialVisualForItem(id),null);
 assert.ok(unequipSlot(g,p,'social_torso').ok);
 assert.equal(g.metaFor(p).sv,undefined);assert.deepEqual(g.metaFor(p).av,{chest:'field_chest'});assert.ok(p.buffs.includes(buff));assert.equal(p.stats,stats);
});
test('owned social equipment survives reload while an unowned social value is removed',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'attunement-social-'));
 t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 const file=path.join(dir,'characters.json'),store=new CharacterStore(file);
 const {char,token}=store.create('Coat Tester','vanguard');
 char.inventory.push('social_relay_coat');char.equipped.social_torso='social_relay_coat';
 store.markDirty();assert.ok(store.flush());
 let restored=new CharacterStore(file),loaded=restored.authenticate(token);
 assert.equal(loaded.equipped.social_torso,'social_relay_coat');
 loaded.equipped.social_torso='social_service_coat';restored.markDirty();assert.ok(restored.flush());
 loaded=new CharacterStore(file).authenticate(token);
 assert.ok(!loaded.equipped.social_torso);
});
test('fitted coat swaps and restores native meshes, preview cache distinguishes actual chosen coat',()=>{
 const geometry=new THREE.BoxGeometry(),original=new THREE.MeshStandardMaterial();
 const chest=new THREE.Mesh(geometry,original),coat=new THREE.Mesh(geometry,original);coat.visible=false;
 const layers=createSocialTorso(THREE,{texture:()=>null},[{mesh:chest,shell:'chest',original,originalVisible:true},{mesh:coat,shell:'coat',original,originalVisible:false}]);
 layers.apply('service');assert.equal(layers.worn(),'service');assert.ok(coat.visible&&!chest.visible);assert.notEqual(coat.material,original);
 layers.apply('relay');assert.equal(layers.worn(),'relay');layers.apply('constructor');assert.equal(layers.worn(),null);
 assert.ok(chest.visible&&!coat.visible);assert.equal(coat.material,original);
 layers.apply('service');layers.dispose();assert.ok(chest.visible&&!coat.visible);assert.equal(coat.material,original);
 const meta=characterPortraitMeta({name:'Test',cls:'vanguard',look:'vanguard_plate'});
 const preview=characterPortraitMeta({name:'Test',cls:'vanguard',look:'vanguard_plate',equipped:{social_torso:'social_relay_coat'}});
 assert.equal(preview.sv,'relay');assert.notEqual(portraitCacheKey(meta,'portrait',true),portraitCacheKey(preview,'portrait',true));
 geometry.dispose();original.dispose();
});
