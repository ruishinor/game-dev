// One command to look at pipeline assets in the game's three.js runtime.
//
//   npm run preview:pipeline            (then open the printed address)
//
// Copies every committed pipeline GLB (tools/asset-pipeline/assets/<id>/outputs/<id>.glb)
// into the git-ignored client/pipeline-assets/, writes its manifest from the clip
// metadata next to it, and starts the game server. No Python or Blender needed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { startServer } from '../../../server/index.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const ASSETS = path.join(ROOT, 'tools', 'asset-pipeline', 'assets');
const PUB = path.join(ROOT, 'client', 'pipeline-assets');
fs.mkdirSync(PUB, { recursive: true });

const models = [];
for (const id of fs.readdirSync(ASSETS)) {
  const out = path.join(ASSETS, id, 'outputs');
  const glb = path.join(out, `${id}.glb`);
  const meta = path.join(out, 'game_ready.json');
  if (!fs.existsSync(glb) || !fs.existsSync(meta)) continue;
  const clips = JSON.parse(fs.readFileSync(meta, 'utf8')).clips || {};
  fs.copyFileSync(glb, path.join(PUB, `${id}.glb`));
  models.push({
    id, file: `${id}.glb`, label: id.charAt(0).toUpperCase() + id.slice(1) + ' (pipeline prototype)',
    clips: Object.fromEntries(Object.entries(clips).map(([name, c]) => [name, {
      loop: !!c.loop,
      ...(typeof c.ground_speed_m_s === 'number' && { speed: c.ground_speed_m_s }),
      ...(c.speed_samples && { speedSamples: c.speed_samples }),
      ...(c.turn_rate_deg_s && { turnDegS: c.turn_rate_deg_s }),
    }])),
  });
}
fs.writeFileSync(path.join(PUB, 'manifest.json'), JSON.stringify({ note: 'Generated by npm run preview:pipeline (git-ignored).', models }, null, 1));
if (!models.length) {
  console.error('No pipeline outputs found under tools/asset-pipeline/assets/*/outputs/.');
  process.exit(1);
}
const port = Number(process.env.PORT || 8080);
const srv = await startServer({ port, host: process.env.HOST || '127.0.0.1', dataFile: null });
console.log(`\nPipeline preview ready: http://127.0.0.1:${srv.port}/client/pipeline-preview.html`);
console.log(`Assets: ${models.map((m) => m.id).join(', ')}   (Ctrl+C to stop)\n`);
