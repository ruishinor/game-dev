// Build the runtime assets under client/assets/ from the source packs in
// .asset-cache/ (see fetch.mjs) according to assets/recipe.mjs, and write
// client/assets/manifest.json describing every output.
//
//   npm run assets:build            build everything
//   npm run assets:build -- nature  build only the named bundles (manifest is merged)

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { HUMANOIDS, KITS, SHELLS, TEXTURES, FACE_TEXTURES } from '../../assets/recipe.mjs';
import { CACHE, LEDGER, fetchAll } from './fetch.mjs';
import { readGltf, mergePieces, hueShift, attachEmissive, optimise, writeGlb, rawSize, triangleCount, simplifySelected } from './lib/gltf.mjs';
import { addRetargetedClips, trimClips, checkRestPose, clipDurations, buildBody } from './lib/humanoid.mjs';
import { LOOK_TEXTURES, renderLookTexture } from './lib/paint.mjs';
import { MakeHuman } from './lib/makehuman.mjs';
import { replaceWithMakeHuman } from './lib/mh-humanoid.mjs';
import { bakeSkin } from './lib/mh-skin.mjs';
import { eyeTexture, lashTexture } from './lib/face-textures.mjs';

// Face and skin maps (one bake, several files). Data: assets/recipe.mjs FACE_TEXTURES.
let skinBake = null;
async function buildFaceTexture(spec) {
  const file = path.join(OUT, spec.out);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const mhDir = path.join(CACHE, 'makehuman');
  let raw;
  if (spec.kind === 'eye') {
    const t = await eyeTexture(mhDir, spec.size);
    raw = { data: t.data, w: t.size, h: t.size };
  } else if (spec.kind === 'lash') {
    const t = lashTexture(spec.w, spec.h);
    raw = { data: t.data, w: t.w, h: t.h };
  } else {
    skinBake ??= bakeSkin(new MakeHuman(mhDir), { size: 2048 });
    raw = { data: Buffer.from(skinBake[spec.kind]), w: skinBake.size, h: skinBake.size };
  }
  let img = sharp(raw.data, { raw: { width: raw.w, height: raw.h, channels: 4 } });
  if (spec.size && spec.size !== raw.w && spec.kind !== 'eye') img = img.resize(spec.size, spec.size);
  if (spec.noAlpha) img = img.removeAlpha();
  await img.webp({ quality: spec.quality ?? 86, alphaQuality: 100, effort: 5, exact: true, ...(spec.lossless && { lossless: true }) }).toFile(file);
  return { kind: 'texture', url: spec.out, bytes: fs.statSync(file).size, hash: hashOf(file), sources: spec.sources.length ? spec.sources : ['original'], note: 'Generated by tools/assets/lib/' + (spec.kind === 'eye' || spec.kind === 'lash' ? 'face-textures.mjs' : 'mh-skin.mjs') };
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'client', 'assets');
const MANIFEST = path.join(OUT, 'manifest.json');

const resolve = ([id, rel]) => {
  const unpacked = path.join(CACHE, id, 'x', rel);
  return fs.existsSync(unpacked) ? unpacked : path.join(CACHE, id, rel);
};
const hashOf = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0, 12);
const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
const known = new Set(LEDGER.sources.map((s) => s.id));
function requireSources(ids, what) {
  for (const id of ids) if (!known.has(id)) throw new Error(`${what}: source "${id}" is not in assets/sources.json — every asset needs recorded provenance`);
}

async function buildHumanoid(spec) {
  const doc = await readGltf(resolve(spec.mesh));
  trimClips(doc, spec.keep);
  if (spec.retarget) {
    const lib = await readGltf(resolve(spec.retarget.from));
    checkRestPose(doc, lib);
    addRetargetedClips(doc, lib, spec.retarget.clips);
  }
  let mh = null;
  if (spec.makehuman) mh = new MakeHuman(path.join(CACHE, 'makehuman'));
  const body = spec.makehuman ? replaceWithMakeHuman(doc, mh, spec.makehuman, SHELLS) : buildBody(doc, SHELLS);
  // Mostly hidden surfaces lose detail; the face, hands and hair keep theirs.
  if (spec.makehuman?.simplify) body.simplified = await simplifySelected(doc, spec.makehuman.simplify);
  const scene = doc.getRoot().getDefaultScene() || doc.getRoot().listScenes()[0];
  const tris = scene.listChildren().reduce((n, c) => n + triangleCount(c), 0);
  const clips = clipDurations(doc);
  const before = await rawSize(doc);
  // The mannequin spends most of its triangles on fingers; halve the count.
  // The MakeHuman body keeps its topology (faces and morph targets).
  await optimise(doc, spec.makehuman ? { simplifyRatio: 0, keepAttributes: true, quantizationVolume: 'scene' } : { simplifyRatio: spec.simplify ?? 0.5 });
  const file = path.join(OUT, spec.out);
  const bytes = await writeGlb(doc, file);
  const after = (doc.getRoot().getDefaultScene() || doc.getRoot().listScenes()[0]).listChildren().reduce((n, c) => n + triangleCount(c), 0);
  return { kind: 'humanoid', url: spec.out, bytes, rawBytes: before, hash: hashOf(file), tris: after, sourceTris: tris, clips, shells: body.shells, ...(body.morphs && { morphs: body.morphs.map(([n]) => n), regions: body.regions }), joints: pick(body.joints, ['pelvis', 'spine_03', 'Head', 'hand_l', 'foot_l']), sources: spec.sources };
}

const pick = (obj, keys) => Object.fromEntries(keys.map((k) => [k, obj[k]]));

async function buildKit(spec) {
  const { doc, pieces } = await mergePieces(spec.pieces, resolve);
  if (spec.hueShift) await doc.transform(hueShift(spec.hueShift.match, spec.hueShift.degrees));
  for (const e of spec.emissive || []) await doc.transform(attachEmissive(e.material, resolve(e.file), e.factor));
  const before = await rawSize(doc);
  await optimise(doc, { maxTexture: spec.maxTexture, simplifyRatio: spec.simplify || 0 });
  const file = path.join(OUT, spec.out);
  const bytes = await writeGlb(doc, file);
  const textures = doc.getRoot().listTextures().length;
  // Report triangle counts as shipped (after any simplification).
  const scene = doc.getRoot().getDefaultScene() || doc.getRoot().listScenes()[0];
  for (const node of scene.listChildren()) if (pieces[node.getName()]) pieces[node.getName()].tris = triangleCount(node);
  return { kind: 'kit', url: spec.out, bytes, rawBytes: before, hash: hashOf(file), tris: Object.values(pieces).reduce((n, p) => n + p.tris, 0), textures, pieces, sources: spec.sources };
}

async function buildTexture(spec) {
  const file = path.join(OUT, spec.out);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  let img = sharp(resolve(spec.src)).resize(spec.size, spec.size);
  // Partly desaturate terrain albedo so zone tints (vertex colours) read through it.
  if (spec.grey) img = img.modulate({ saturation: 1 - spec.grey });
  await img.webp({ quality: spec.quality, effort: 5 }).toFile(file);
  return { kind: 'texture', url: spec.out, bytes: fs.statSync(file).size, hash: hashOf(file), sources: [spec.src[0]] };
}

async function buildLookTexture(spec) {
  const file = path.join(OUT, spec.out);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  await renderLookTexture(spec, file);
  return { kind: 'texture', url: spec.out, bytes: fs.statSync(file).size, hash: hashOf(file), sources: ['original'], note: 'Generated by tools/assets/lib/paint.mjs' };
}

async function main() {
  const only = new Set(process.argv.slice(2));
  const jobs = [
    ...HUMANOIDS.map((s) => [s, buildHumanoid]),
    ...KITS.map((s) => [s, buildKit]),
    ...TEXTURES.map((s) => [s, buildTexture]),
    ...LOOK_TEXTURES.map((s) => [{ ...s, sources: [] }, buildLookTexture]),
    ...FACE_TEXTURES.map((s) => [s, buildFaceTexture]),
  ];
  const unknown = [...only].filter((id) => !jobs.some(([spec]) => spec.id === id));
  if (unknown.length) throw new Error(`unknown output: ${unknown.join(', ')}`);

  const selected = only.size ? jobs.filter(([spec]) => only.has(spec.id)) : jobs;
  const sourceIds = new Set();
  for (const [spec] of selected) {
    const sources = spec.sources || [spec.src[0]];
    requireSources(sources, spec.id);
    for (const source of sources) sourceIds.add(source);
  }
  await fetchAll({ log: () => {}, sourceIds });
  fs.mkdirSync(OUT, { recursive: true });
  const assets = only.size && fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')).assets : {};

  for (const [spec, build] of selected) {
    const t0 = Date.now();
    assets[spec.id] = await build(spec);
    const a = assets[spec.id];
    console.log(`${spec.id.padEnd(22)} ${kb(a.bytes).padStart(9)}${a.rawBytes ? `  (source ${kb(a.rawBytes)}, ${Math.round((1 - a.bytes / a.rawBytes) * 100)}% smaller)` : ''}${a.tris ? `  ${a.tris} tris` : ''}  ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
  const manifest = {
    version: 1,
    note: 'Generated by tools/assets/build.mjs. Do not edit. Provenance for each source id is in assets/sources.json.',
    assets: Object.fromEntries(Object.entries(assets).sort(([a], [b]) => a.localeCompare(b))),
  };
  fs.writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 1)}\n`);
  const total = Object.values(assets).reduce((n, a) => n + a.bytes, 0);
  console.log(`total ${kb(total)} in ${Object.keys(assets).length} assets -> ${path.relative(ROOT, MANIFEST)}`);
}

main().catch((err) => {
  console.error(`assets:build failed: ${err.stack || err.message}`);
  process.exit(1);
});
