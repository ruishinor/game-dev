"""Install the exact owner-approved, previously prepared 26-recording library."""
import hashlib
import json
from pathlib import Path
import shutil
import sys

MANIFEST_HASH = "e72e069fc484833c55b80a980c2d271fdf9d3ca08602bd862394375d7b8c5d74"
PREFIX = "// Generated by tools/voice/promote.py from explicit review decisions.\nexport const APPROVED_RADIO_ASSETS=Object.freeze("
SUFFIX = ");\n"

def sha(data):
    return hashlib.sha256(data).hexdigest()

def install(source, root):
    raw = (source / "src/radio-assets.js").read_bytes()
    if sha(raw) != MANIFEST_HASH:
        raise ValueError("Unexpected approved manifest bytes")
    text = raw.decode("utf-8")
    if not text.startswith(PREFIX) or not text.endswith(SUFFIX):
        raise ValueError("Unexpected manifest format")
    manifest = json.loads(text[len(PREFIX):-len(SUFFIX)])
    clips = source / "assets/voice"
    expected = {key + ".mp3" for key in manifest}
    if len(expected) != 26 or {p.name for p in clips.iterdir()} != expected:
        raise ValueError("Expected exact 26-file recording library")
    for key, asset in manifest.items():
        clip = clips / (key + ".mp3")
        if sha(clip.read_bytes()) != asset["sha256"]:
            raise ValueError("Recording hash mismatch: " + key)
        asset["provenance"]["distributionScope"] = "noncommercial-playtest"
        asset["provenance"]["reviewer"] = "Attunement project owner"
        asset["provenance"]["listeningNotes"] = "Owner explicitly approved all ready recordings on 2026-11-18; original MP3 bytes unchanged."
        asset["provenance"]["rightsNotes"] = ("Owner authorized incorporation in the noncommercial playtest. "
            "Kokoro-82M pinned revision is Apache-2.0; upstream per-voice training provenance remains incompletely documented. "
            "Not a commercial or general release clearance. No model weights redistributed.")
    target = root / "client/assets/voice"
    if target.exists() and {p.name for p in target.iterdir()} - expected:
        raise ValueError("Refusing to overwrite unrelated voice assets")
    target.mkdir(parents=True, exist_ok=True)
    for name in sorted(expected):
        shutil.copyfile(clips / name, target / name)
    out = root / "client/src/radio-assets.js"
    out.write_bytes(("// Exact approved recordings; see docs/art/VOICE-CREDITS.md.\nexport const APPROVED_RADIO_ASSETS=Object.freeze("
        + json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + ");\n").encode("utf-8"))
    print("Verified and installed 26 byte-identical MP3 files")

if __name__ == "__main__":
    install(Path(sys.argv[1]), Path(sys.argv[2]) if len(sys.argv)>2 else Path.cwd())
